namespace Syncfusion.Maui.Toolkit.InteractiveViewer
{
	/// <summary>
	/// Defines the panning axis for the <see cref="SfInteractiveViewer"/>.
	/// </summary>
	public enum PanAxis
	{
		/// <summary>
		/// Allows panning in both horizontal and vertical directions.
		/// </summary>
		Both,

		/// <summary>
		/// Allows panning only in the horizontal direction.
		/// </summary>
		Horizontal,

		/// <summary>
		/// Allows panning only in the vertical direction.
		/// </summary>
		Vertical,
	}
}